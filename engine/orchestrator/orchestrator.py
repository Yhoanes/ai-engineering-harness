from __future__ import annotations

import re
from datetime import UTC, datetime
from pathlib import Path

from engine.context.loader import load_context
from engine.router.models import RouteDecision

from .models import OrchestratorHandoff


def next_task_id(existing_ids: list[str], prefix: str = "TASK") -> str:
    if not re.match(r"^[A-Z0-9_-]+$", prefix):
        raise ValueError(f"Invalid prefix: {prefix}")

    max_num = 0
    pattern = re.compile(rf"^{re.escape(prefix)}-(\d{{4}})$")
    for tid in existing_ids:
        m = pattern.match(tid)
        if m:
            max_num = max(max_num, int(m.group(1)))

    return f"{prefix}-{max_num + 1:04d}"


def prepare_handoff(
    decision: RouteDecision,
    project_key: str,
    repo_root: Path,
    existing_task_ids: list[str] | None = None,
    task_id: str | None = None,
    existing_contract: dict | None = None,
) -> OrchestratorHandoff:
    # 1. Validation
    wf_path = repo_root / "core" / "workflows" / decision.workflow_id
    if not wf_path.is_dir():
        raise ValueError(f"Workflow nonexistent: {decision.workflow_id}")

    spec_path = repo_root / "core" / "specialists" / decision.primary_specialist
    if not spec_path.is_dir():
        raise ValueError(f"Specialist nonexistent: {decision.primary_specialist}")

    # 2. Context Loading
    bundle = load_context(repo_root, project_key, level=decision.context_level, task_id=task_id)

    # 3. Draft Contract
    task_contract = existing_contract
    if decision.workflow_id == "plan-task":
        tid = next_task_id(existing_task_ids or [], prefix="TASK")
        task_contract = {
            "task_id": tid,
            "task_type": "standard",
            "title": "Draft Task",
            "description": "Generated by Orchestrator.",
            "project": project_key,
            "status": "awaiting_approval",
            "approval_status": "pending",
            "approved_by": None,
            "approved_at": None,
            "acceptance_status": "pending",
            "deviation": {
                "documented": False,
                "description": None,
                "impact": None,
                "accepted_by": None,
                "accepted_at": None,
            },
            "implementation_baseline": {
                "git_head": None,
                "working_tree_clean": None,
                "captured_at": None,
                "preexisting_untracked": [],
            },
            "scope": {
                "planned_paths": {"modify": ["TBD"], "read": []},
                "allowed_actions": {"terminal": [], "web": []},
                "forbidden_actions": [],
            },
            "assigned_workflow": "implement-task",
            "assigned_specialists": [],
            "evidence": {
                "tests": {"status": None},
                "code_review": {"status": None},
                "security_review": {"status": None},
            },
            "postcheck": {"status": None},
            "approval_history": [],
            "acceptance_history": [],
            "created_at": datetime.now(UTC).isoformat(),
            "updated_at": datetime.now(UTC).isoformat(),
            "acceptance_criteria": [],
        }

    # Restrictions based on authority matrix logic
    restrictions = []
    if decision.workflow_id == "discuss":
        restrictions.append("NO_IMPLEMENTATION")
        restrictions.append("NO_STATE_CHANGES")

    return OrchestratorHandoff(
        project=project_key,
        workflow=decision.workflow_id,
        primary_specialist=decision.primary_specialist,
        supporting_specialists=decision.supporting_specialists,
        context_bundle=bundle,
        task_contract=task_contract,
        restrictions=restrictions,
        next_action=f"Execute {decision.workflow_id} via {decision.primary_specialist}",
    )
